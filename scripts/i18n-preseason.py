def run(lang, block):
    p = f'src/shared/i18n/locales/{lang}.ts'
    s = open(p, encoding='utf-8').read()
    if '  pilot: {' not in s:
        i = s.index('  settings: {')
        s = s[:i] + block + s[i:]
    for old, new in REPL[lang]:
        if old in s:
            s = s.replace(old, new, 1)
        else:
            print(f'[{lang}] no encontrado: {old[:70]}')
    open(p, 'w', encoding='utf-8').write(s)


